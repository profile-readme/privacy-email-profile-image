// Rasterize the glyphs used in email addresses into a compact bitmap table.
// Output: src/email/font.generated.js (deflated 8-bit coverage per glyph cell).
// Font: DejaVu Sans Mono Bold (Bitstream Vera license, see LICENSE-FONT). Requires ImageMagick.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { deflateSync } from "node:zlib";

const FONT = process.env.FONT || "DejaVu-Sans-Mono-Bold";
const POINT = 40;
const CHARS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.@_-+";

const magick = (argv) => {
  for (const bin of ["magick", "convert"]) {
    try { return execFileSync(bin, argv, { maxBuffer: 16 << 20 }); }
    catch (e) { if (e.code !== "ENOENT") throw e; }
  }
  throw new Error("ImageMagick not found");
};

let W = 0, H = 0;
const cells = [];
for (const c of CHARS) {
  // A leading "@" makes label: read a file, so escape it.
  const text = c === "@" ? "\\@" : c;
  const args = ["-background", "black", "-fill", "white", "-font", FONT, "-pointsize", String(POINT), `label:${text}`];
  const [w, h] = magick([...args, "-format", "%w %h", "info:"]).toString().split(" ").map(Number);
  if (!W) { W = w; H = h; }
  if (w !== W || h !== H) throw new Error(`glyph ${c} is ${w}x${h}, expected monospace ${W}x${H}`);
  cells.push(magick([...args, "-colorspace", "gray", "-depth", "8", "gray:-"]));
}
const packed = deflateSync(Buffer.concat(cells), { level: 9 });
writeFileSync("src/email/font.generated.js",
  `// SPDX-FileCopyrightText: 2003 Bitstream, Inc. (glyph outlines); DejaVu changes are public domain\n` +
  `// SPDX-License-Identifier: LicenseRef-Bitstream-Vera\n` +
  `// GENERATED by scripts/build-font.mjs from ${FONT} at ${POINT}pt. Do not edit by hand.\n` +
  `export const FONT = ${JSON.stringify({ chars: CHARS, w: W, h: H })};\n` +
  `export const FONT_DATA = "${packed.toString("base64")}";\n`);
console.log(`src/email/font.generated.js: ${CHARS.length} glyphs, cell ${W}x${H}, ${(packed.length / 1024).toFixed(1)} KiB deflated`);
